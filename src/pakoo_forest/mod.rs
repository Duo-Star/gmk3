// src/pakoo_forest/mod.rs

//! `pakoo_forest` —— gmk3 的数学内核。
//!
//! 面向命令式数值计算几何：
//!
//! 1. 射影平面 + 无穷远直线 + 两个虚圆点；
//! 2. 基于矩阵与齐次坐标表示圆锥曲线、点、直线，运算在复数域上封闭；
//! 3. 复量抽象，按射影几何的成对（对偶）关系组织类型。
//!
//! 当前提供：
//!
//! - [`calc::Complex`]：复数标量；
//! - [`calc::Vec3C`] / [`calc::Cov3C`]：复列向量 / 行向量；
//! - [`calc::Mat3C`]：3×3 复矩阵；
//! - [`geo::Dot`] / [`geo::Line`]：射影平面上的齐次点 / 齐次直线
//!   （含无穷远直线与两个虚圆点，关联、连线、交点、平行、垂直判定）；
//! - [`geo::Conic`]：二次曲线（圆锥曲线），含对偶、极线/切线与完整类型判定。
//!
//! `calc` 为与几何解耦的纯线性代数类型，`geo` 以 Newtype 在其上定义几何语义。

pub mod calc;
pub mod geo;

use geo::Conic;
use geo::Dot;
use geo::Line;
